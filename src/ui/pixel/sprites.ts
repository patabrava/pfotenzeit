export const SPRITE_NAMES: readonly string[] = SPRITES.map((s) => s.name);

/** Resolve the sprite for a profile state and growth stage; adult falls back to growing (no adult art in the MVP). */
export function findSprite(state: PixelState, growth: GrowthStage): PixelSprite {
  if (state === 'memorial') return SPRITES.find((s) => s.state === 'memorial') as PixelSprite;
  const stage = growth === 'arriving' ? 'arriving' : 'growing';
  const found = SPRITES.find((s) => s.state === state && s.stage === stage);
  return found ?? (SPRITES.find((s) => s.state === 'awake' && s.stage === stage) as PixelSprite);
}
